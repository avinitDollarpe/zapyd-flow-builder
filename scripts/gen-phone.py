#!/usr/bin/env python3
"""Generate public/rates/phone.js: every region libphonenumber dials, its country
code and the national number pattern of its mobile and fixed-line numbers, for
the rates page's phone field (the country picker and the number check).

Run: pip install phonenumbers && python3 scripts/gen-phone.py
"""
import json
import os

import phonenumbers
from phonenumbers.phonemetadata import PhoneMetadata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "public", "rates", "phone.js")
SKIP = {"001", "AC", "TA"}  # non-geographic, and two regions flag-icons has no flag for

regions = {}
for region in sorted(phonenumbers.SUPPORTED_REGIONS - SKIP):
    md = PhoneMetadata.metadata_for_region(region)
    patterns = [d.national_number_pattern for d in (md.mobile, md.fixed_line) if d and d.national_number_pattern]
    regions[region.lower()] = [str(md.country_code), "|".join(dict.fromkeys(patterns))]

with open(OUT, "w") as f:
    f.write(f"// Generated by scripts/gen-phone.py from libphonenumber {phonenumbers.__version__}. Do not edit.\n")
    f.write("// iso2: [country code, national number pattern of its mobile and fixed-line numbers]\n")
    f.write(f"window.PHONE = {json.dumps(regions, separators=(',', ':'))}\n")
print(f"wrote {OUT}: {len(regions)} regions")
